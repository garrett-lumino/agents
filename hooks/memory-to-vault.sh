#!/bin/sh
# SessionStart hook: keep every Claude Code project memory dir inside the
# Obsidian vault. Each ~/.claude/projects/<p>/memory becomes a symlink to
# $VAULT_MEM/<short name>, so the vault holds the only copy and any tool
# reading the vault sees what Claude remembers.
VAULT_MEM="${AGENTS_VAULT:-$HOME/dev/obsidian}/claude-memory"
PROJECTS="$HOME/.claude/projects"
PREFIX=$(printf '%s' "$HOME/dev/github/" | tr '/' '-')

input=$(cat)
[ -d "$VAULT_MEM" ] || exit 0 # vault missing: leave memory where it is

short_name() {
  n=${1#"$PREFIX"}
  printf '%s' "${n#-}"
}

# Move one real memory dir into the vault and leave a symlink behind.
link_project() {
  mem="$1/memory"
  target="$VAULT_MEM/$(short_name "$(basename -- "$1")")"
  [ -L "$mem" ] && return 0
  if [ -d "$mem" ]; then
    if [ -e "$target" ]; then
      for f in "$mem"/* "$mem"/.[!.]*; do
        [ -e "$f" ] && mv -n -- "$f" "$target"/
      done
      rmdir -- "$mem" 2>/dev/null || return 1 # name clash: keep both, retry next run
    else
      mv -- "$mem" "$target" || return 1
    fi
  elif [ "$2" = current ]; then
    mkdir -p -- "$target" || return 1 # new project: start it in the vault
  else
    return 0
  fi
  ln -s -- "$target" "$mem"
}

for proj in "$PROJECTS"/*/; do
  link_project "${proj%/}" sweep
done

# The session's own project may have no memory dir yet; create it in the vault.
transcript=$(printf '%s' "$input" | jq -r '.transcript_path // empty' 2>/dev/null)
if [ -n "$transcript" ]; then
  link_project "$(dirname -- "$transcript")" current
fi

# Shared memory for every project: hand its index to the session as context.
GLOBAL="$VAULT_MEM/_global"
mkdir -p -- "$GLOBAL"
[ -f "$GLOBAL/MEMORY.md" ] || printf '# Global Memory Index\n' >"$GLOBAL/MEMORY.md"
project_mem=""
[ -n "$transcript" ] && project_mem=$(cd "$(dirname -- "$transcript")/memory" 2>/dev/null && pwd -P)
problems=$("$(dirname -- "$0")/memory-lint.sh" ${project_mem:+"$project_mem"} "$GLOBAL")
context=$(
  printf 'Global memory (shared by every project and AI tool) lives in %s.\n' "$GLOBAL"
  printf 'Its index is below. Open a file there when an entry is relevant. To save a memory that applies across projects (not just this one), write it in that folder in the usual memory format and add a line to its MEMORY.md.\n\n'
  head -n 200 -- "$GLOBAL/MEMORY.md"
  if [ -n "$problems" ]; then
    printf '\nMemory problems found (fix them when convenient, then keep the index in step):\n%s\n' "$problems"
  fi
  if [ "$(printf '%s' "$input" | jq -r '.source // empty' 2>/dev/null)" = compact ]; then
    printf '\nThe conversation was just compacted. Check the summary for durable facts, decisions or feedback not yet saved to memory, and save them now.\n'
  fi
)
jq -n --arg c "$context" '{hookSpecificOutput: {hookEventName: "SessionStart", additionalContext: $c}}'

# Regenerate the index note from the folders present.
{
  cat <<'EOF'
---
title: Claude Memory
tags: [claude/memory, type/moc]
status: active
---

# Claude Memory

Generated by `~/agents/hooks/memory-to-vault.sh` at each Claude Code session start; edits here are overwritten.

Claude Code's persistent memory, one folder per project. These are the live files:
each `~/.claude/projects/<project>/memory` is a symlink into this folder.

Format, for any tool reading or writing here:
- `MEMORY.md` in each folder is the index Claude loads at session start: one line per memory, `- [Title](file.md) — hook`.
- Every other `.md` file holds one fact, with frontmatter `name` (kebab-case slug, matches the filename), `description` (one line) and `metadata.type` (user | feedback | project | reference).
- Links between memories are `[[name]]`.
- Add a line to `MEMORY.md` for every new memory file, or Claude will not see it.

## Global

- [[_global/MEMORY|_global]]: loaded into every Claude Code session in every project. Put facts and rules that apply everywhere here.

## Projects

EOF
  for d in "$VAULT_MEM"/*/; do
    p=$(basename -- "$d")
    [ "$p" = _global ] && continue
    if [ -f "$d/MEMORY.md" ]; then
      printf -- '- [[%s/MEMORY|%s]]\n' "$p" "$p"
    else
      # shellcheck disable=SC2016 # backticks are Markdown code, not a command
      printf -- '- `%s/` (no index yet)\n' "$p"
    fi
  done
} >"$VAULT_MEM/Claude Memory.md.tmp" && mv -- "$VAULT_MEM/Claude Memory.md.tmp" "$VAULT_MEM/Claude Memory.md"

exit 0
